const lines = rawText.split('\n');
const categoryMap = {
  '1. NATIONAL AFFAIRS': 'national',
  '2. INTERNATIONAL AFFAIRS': 'international',
  '3. ECONOMY': 'economy',
  '4. BANKING & FINANCE': 'banking',
  '5. SCIENCE & TECHNOLOGY': 'science',
  '6. DEFENCE': 'defence',
  '7. ENVIRONMENT': 'environment',
  '8. SPORTS': 'sports',
  '9. AWARDS & HONORS': 'awards',
  '10. GOVERNMENT SCHEMES': 'government_schemes',
  '11. APPOINTMENTS': 'appointments',
  '12. STATE NEWS (UP + Other States)': 'state_news'
};

let currentCategory = null;
let parsedItems = [];
let itemBuffer = [];
let isHighImportance = false;

for (let i = 0; i < lines.length; i++) {
  const line = lines[i];
  const trimmed = line.trim();

  // Check if it is a category header
  let matchedCat = null;
  for (const [key, catVal] of Object.entries(categoryMap)) {
    if (trimmed.includes(key)) {
      matchedCat = catVal;
      break;
    }
  }

  if (matchedCat) {
    // Flush current item before changing category
    if (itemBuffer.length > 0) {
      parsedItems.push({
        category: currentCategory,
        importance: isHighImportance ? 'high' : 'medium',
        text: itemBuffer.join(' ').replace(/\s+/g, ' ').trim()
      });
      itemBuffer = [];
    }
    currentCategory = matchedCat;
    continue;
  }

  if (trimmed.startsWith('IMPORTANT DAYS')) {
    // Finished parsing categories we care about
    currentCategory = null;
  }

  if (!currentCategory) continue;

  // We are inside a category. Determine if this line starts a new item.
  // A new item starts with '★ ' or '  ' but NOT '    '
  const startsWithStar = line.startsWith('★ ') || trimmed.startsWith('★');
  const startsWithTwoSpaces = line.startsWith('  ') && !line.startsWith('    ') && trimmed.length > 0;
  
  // Noun separator check: if it looks like "Aritra Rai — climbed..." it starts with space but has an em-dash.
  // But wait, what if a line starts with 2 spaces and is a continuation of the previous line?
  // Let's see: usually continuation lines do NOT contain '—' or '–' or '='.
  // Exception: Padma awards total: "131 total: 5 Padma..." doesn't have an em-dash.
  // So let's check: if (startsWithStar || (startsWithTwoSpaces && (trimmed.includes('—') || trimmed.includes('–') || trimmed.includes('=') || trimmed.includes('→') || trimmed.includes('announced') || trimmed.includes('appointed') || trimmed.includes('won') || trimmed.includes('won') || trimmed.includes('defeated') || trimmed.includes('surpassed'))))
  // Wait, let's see. Let's make it simpler.
  // Is it possible to split the category block by searching for "★" or "  " and manually fixing any continuation lines?
  // Yes! If we do:
  const isNewItem = startsWithStar || (startsWithTwoSpaces && (trimmed.includes('—') || trimmed.includes('–') || trimmed.includes('=') || trimmed.includes('→') || trimmed.startsWith('UTTAR PRADESH:') || trimmed.startsWith('OTHER STATES:')));
  
  if (isNewItem) {
    if (itemBuffer.length > 0) {
      parsedItems.push({
        category: currentCategory,
        importance: isHighImportance ? 'high' : 'medium',
        text: itemBuffer.join(' ').replace(/\s+/g, ' ').trim()
      });
      itemBuffer = [];
    }
    isHighImportance = startsWithStar;
    itemBuffer.push(trimmed.replace(/^★\s*/, ''));
  } else {
    if (trimmed.length > 0 && !trimmed.startsWith('━━━')) {
      itemBuffer.push(trimmed);
    }
  }
}

if (itemBuffer.length > 0) {
  parsedItems.push({
    category: currentCategory,
    importance: isHighImportance ? 'high' : 'medium',
    text: itemBuffer.join(' ').replace(/\s+/g, ' ').trim()
  });
}

console.log(`Total parsed items: ${parsedItems.length}`);
