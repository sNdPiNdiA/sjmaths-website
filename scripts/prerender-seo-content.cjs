// Materialize authored content with the SAME renderer used by the site.
// No network access, analytics, authentication, timed tests or AI generation.
const fs = require('fs');
const path = require('path');
const { chromium } = require('playwright');
const policy = require('./seo-policy.cjs');
const { ROOT, siteFiles, parse, applyEdits } = require('./seo-html.cjs');
const { createResolver } = require('./seo-routes.cjs');

function getTargetSelector(source) {
  const $ = parse(source);
  if ($('#upsc-page-data').length) return '#topic-content';
  if ($('#question-container').length) return '#question-container';
  if ($('#questionContainer').length) return '#questionContainer';
  return null;
}

async function main() {
  const files = siteFiles();
  const resolve = createResolver(files, []);
  const retry = process.argv.includes('--retry-failed');
  const scopes = process.argv.filter(arg => arg.startsWith('--scope='))
    .map(arg => arg.slice('--scope='.length).trim().replace(/\\/g, '/').replace(/^\.\//, '').replace(/\/+$/, ''));
  if (scopes.some(scope => !scope || scope.startsWith('/') || scope.split('/').includes('..'))) {
    throw new Error('Each --scope must be a non-empty repository-relative path without .. segments.');
  }
  const prior = retry ? JSON.parse(fs.readFileSync(path.join(ROOT, 'scratch/seo-prerender.json'), 'utf8')) : [];
  const retryFiles = new Set(prior.filter(row => row.error).map(row => row.file));
  const candidates = files.filter(policy.isManagedHtmlPath)
    .filter(file => !scopes.length || scopes.some(scope => {
      const normalizedFile = file.replace(/\\/g, '/');
      return normalizedFile === scope || normalizedFile.startsWith(`${scope}/`);
    }))
    .filter(file => !retry || retryFiles.has(file)).filter(file => {
    const source = fs.readFileSync(path.join(ROOT, file), 'utf8');
    if (policy.hasNoindex(source) || !/(?:questions-loader|upsc-renderer|render-questions)(?:\.min)?\.js/.test(source)) return false;
    const selector = getTargetSelector(source);
    if (!selector) return false;
    const $ = parse(source);
    const target = $(selector);
    const text = target.text().trim();
    // Never replace manually authored initial HTML or an interactive test.
    return target.length && (!text || /^Loading[\s\S]{0,80}$/i.test(text) || target.html().includes('Initial HTML generated by scripts/prerender-seo-content.cjs'));
  });
  const browser = await chromium.launch({ headless: true });
  const results = prior.filter(row => !row.error);
  let completed = 0;
  try {
    let cursor = 0;
    const renderFile = async file => {
      const original = fs.readFileSync(path.join(ROOT, file), 'utf8');
      const $ = parse(original);
      const selector = getTargetSelector(original);
      if (!selector) throw new Error('No supported authored-content container found.');
      const upsc = selector === '#topic-content';
      const target = $(selector)[0];
      if (!target?.sourceCodeLocation?.endTag) return;
      const renderer = upsc ? 'upsc-renderer.js' : selector === '#questionContainer' ? 'render-questions.js' : 'questions-loader.js';
      const rendererPath = selector === '#questionContainer'
        ? path.join(ROOT, 'questions-module/js', renderer)
        : path.join(ROOT, 'assets/js', renderer);
      const url = policy.toUrl(file);
      const context = await browser.newContext();
      const page = await context.newPage();
      const errors = [];
      page.on('pageerror', error => errors.push(error.message));
      page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
      // Retain only authored data and the renderer. Capture just its container.
      const questionsPath = original.match(/window\.QUESTIONS_JSON\s*=\s*(['"])(.*?)\1/)?.[2];
      $('script').not('#upsc-page-data').remove();
      $('link, style, img, iframe').remove();
      $(selector).empty();
      if (questionsPath) $('body').append(`<script>window.QUESTIONS_JSON=${JSON.stringify(questionsPath).replace(/</g, '\\u003c')}</script>`);
      $('body').append('<script src="/__seo-renderer.js"></script>');
      const harness = $.html();
      await page.route('**/*', async route => {
        const requested = new URL(route.request().url());
        if (requested.href === url) return route.fulfill({ contentType: 'text/html; charset=utf-8', body: harness });
        if (requested.origin !== policy.DOMAIN) return route.abort();
        if (requested.pathname === '/__seo-renderer.js') return route.fulfill({ contentType: 'application/javascript', body: fs.readFileSync(rendererPath) });
        const asset = resolve(requested.href).file;
        if (asset?.endsWith('.json')) return route.fulfill({ contentType: 'application/json; charset=utf-8', body: fs.readFileSync(path.join(ROOT, asset)) });
        return route.abort();
      });
      try {
        await page.goto(url, { waitUntil: 'load' });
        await page.waitForFunction(sel => {
          const el = document.querySelector(sel);
          return el && el.querySelector('.study-tab-footer, .question-card');
        }, selector, { timeout: 5000 });
        if (errors.length) throw new Error(errors.join('; '));
        const rendered = await page.locator(selector).evaluate(el => {
          const copy = el.cloneNode(true);
          copy.querySelectorAll('.study-tab-footer').forEach(node => node.remove());
          return copy.innerHTML.replace(/[ \t]+(?=\r?\n)/g, '').trim();
        });
        if (/Rendering failed|Failed to load questions/.test(rendered)) throw new Error('Renderer failed');
        const loc = target.sourceCodeLocation;
        const eol = original.includes('\r\n') ? '\r\n' : '\n';
        const renderedHtml = rendered.replace(/\r?\n/g, eol);
        const text = `${eol}<!-- Initial HTML generated by scripts/prerender-seo-content.cjs; edit the authored JSON, then regenerate. -->${eol}${renderedHtml}${eol}`;
        const next = applyEdits(original, [{ start: loc.startTag.endOffset, end: loc.endTag.startOffset, text }]);
        if (next !== original) fs.writeFileSync(path.join(ROOT, file), next);
        results.push({ file, changed: next !== original, renderer });
      } catch (error) {
        results.push({ file, error: [error.message, ...errors].join('; ') });
      } finally { await context.close(); }
      completed++;
      if (completed % 25 === 0) console.log(`Prerendered ${completed}/${candidates.length}`);
    };
    await Promise.all(Array.from({ length: 6 }, async () => {
      while (cursor < candidates.length) await renderFile(candidates[cursor++]);
    }));
  } finally { await browser.close(); }
  fs.mkdirSync(path.join(ROOT, 'scratch'), { recursive: true });
  fs.writeFileSync(path.join(ROOT, 'scratch/seo-prerender.json'), JSON.stringify(results, null, 2) + '\n');
  const failures = results.filter(row => row.error);
  console.log(JSON.stringify({ scopes: scopes.length ? scopes : ['all managed pages'], inspected: results.length, rendered: results.length - failures.length, changed: results.filter(row => row.changed).length, failureCount: failures.length, failures: failures.slice(0, 10) }, null, 2));
  if (failures.length) process.exitCode = 1;
}
main().catch(error => { console.error(error); process.exitCode = 1; });
