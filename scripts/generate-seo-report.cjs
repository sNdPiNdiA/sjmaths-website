const fs = require('fs');
const path = require('path');
const { ROOT } = require('./seo-html.cjs');
const read = relative => JSON.parse(fs.readFileSync(path.join(ROOT, relative), 'utf8'));
const finalPath = process.argv.find(arg => arg.startsWith('--audit='))?.slice(8) || 'scratch/seo-final.json';
const baseline = read('scratch/seo-baseline.json');
const final = read(finalPath);
const preservation = read('scratch/seo-preservation.json');
const browser = read('scratch/seo-browser/results.json');
const physicsBrowser = fs.existsSync(path.join(ROOT, 'scratch/seo-browser/physics-results.json')) ? read('scratch/seo-browser/physics-results.json') : [];
const prerender = read('scratch/seo-prerender.json');
const unavailable = read('scripts/reports/seo-unavailable-resources.json');
const marker = '<!-- Initial HTML generated by scripts/prerender-seo-content.cjs; edit the authored JSON, then regenerate. -->';
let prerendered = 0, prerenderBytes = 0, largest = [];
for (const page of final.pages) {
  const full = path.join(ROOT, page.file);
  const source = fs.readFileSync(full, 'utf8');
  if (!source.includes(marker)) continue;
  const bytes = Buffer.byteLength(source);
  prerendered++; prerenderBytes += bytes; largest.push({ file: page.file, bytes });
}
largest.sort((a, b) => b.bytes - a.bytes);
const finalIssues = final.issues.filter(issue => issue.severity !== 'info');
const bySeverity = severity => finalIssues.filter(issue => issue.severity === severity);
const count = (report, code) => report.summary.counts[code] || 0;
const deltaRows = [
  ['Broken internal links', 'broken-internal-link'],
  ['Missing local assets', 'missing-local-asset'],
  ['Missing/multiple canonicals', 'canonical-missing-or-multiple'],
  ['Canonical mismatches', 'canonical-not-normalized'],
  ['Missing social metadata', 'social-missing'],
  ['Duplicate IDs', 'duplicate-id'],
  ['Missing/multiple H1', 'h1-missing-or-multiple'],
  ['Invalid breadcrumbs', 'breadcrumb-invalid'],
  ['Invalid JSON-LD', 'jsonld-invalid'],
  ['Unfetchable sitemap URLs', 'sitemap-unfetchable-url'],
  ['Indexable pages omitted from sitemap', 'indexable-not-in-sitemap'],
  ['Duplicate titles', 'duplicate-title'],
  ['Duplicate descriptions', 'duplicate-description'],
];
const rows = deltaRows.map(([label, code]) => `| ${label} | ${count(baseline, code)} | ${count(final, code)} |`).join('\n');
const noindex = final.pages.filter(page => page.noindex).length;
const aliases = final.pages.filter(page => page.alias).length;
const browserPassed = browser.filter(row => row.passed).length;
const browserStructuralPassed = browser.filter(row => row.structuralPassed).length;
const browserBlocked = browser.filter(row => row.integrationBlocked).length;
const physicsStructuralPassed = physicsBrowser.filter(row => row.structuralPassed).length;
const failureLines = finalIssues.length ? finalIssues.slice(0, 50).map(issue => `- \`${issue.code}\` — \`${issue.file}\`: ${JSON.stringify(issue.detail).slice(0, 220)}`).join('\n') : '- None.';
const report = `# SJMaths SEO audit and remediation

Date: 2026-09-14
Scope: the full local static-site source tree, routing rules, metadata, structured data, internal references, generated search index/sitemaps, and representative browser behavior.

## Outcome

| Measure | Baseline | Final |
| --- | ---: | ---: |
| HTML files inspected | ${baseline.summary.htmlFiles} | ${final.summary.htmlFiles} |
| Indexable pages | ${baseline.summary.indexablePages} | ${final.summary.indexablePages} |
| Sitemap URLs | ${baseline.summary.sitemapUrls} | ${final.summary.sitemapUrls} |
| Hard errors | ${baseline.summary.errors} | ${final.summary.errors} |
| Warnings | ${baseline.summary.warnings} | ${final.summary.warnings} |

${rows}

Final classification: ${noindex} pages carry an explicit noindex directive and ${aliases} source documents are aliases/redirects. The sitemap contains ${final.summary.sitemapUrls} fetchable, canonical, indexable URLs.

## Remediation completed

- Added a source-preserving metadata policy and full-repository SEO audit instead of serializing/reformatting educational HTML.
- Normalized canonical and Open Graph URLs, filled missing social metadata, repaired headings and duplicate IDs, and removed invalid alternate-language declarations.
- Removed route rules that swallowed real lessons or public JSON; repaired internal links and marked ${unavailable.length} links to genuinely unpublished resources as visibly unavailable rather than leaving broken URLs.
- Marked verified placeholder shells noindex while keeping them accessible to crawlers, navigation and future authors. No placeholder file or syllabus entry was deleted.
- Generated missing topic directory pages only from existing lessons and split sitemap output by maintained subject groups.
- Materialized the existing renderer's initial authored content in ${prerendered} dynamic pages (${(prerenderBytes / 1048576).toFixed(1)} MiB total, ${(prerenderBytes / Math.max(prerendered, 1) / 1024).toFixed(1)} KiB average), while retaining the interactive renderer for later tabs.
- Rebuilt the three modified minified SEO/client assets and refreshed their cache keys.
- Repaired malformed Class 9 exercise document containers, malformed UPSSSC embedded JSON, and malformed Class 12 Physics KaTeX/script endings.
- Sitemap lastmod is emitted only when a real content date is known; checkout timestamps are not published as update dates.

Largest prerendered source pages (monitor as authored content grows):
${largest.slice(0, 5).map(row => `- \`${row.file}\` — ${(row.bytes / 1024).toFixed(1)} KiB`).join('\n') || '- None.'}

## Verification

- Static audit: ${final.summary.errors} errors, ${final.summary.warnings} warnings, ${final.summary.informational || 0} informational review signals.
- Preservation comparison: ${preservation.uniqueContentItems} unique educational/data fragments checked across ${preservation.checkedPages} modified pages; ${preservation.failures.length} losses. ${preservation.recoveredInvalidEmbeddedData || 0} malformed inline data blocks were recovered from their valid authored data files.
- Dynamic prerender: ${prerender.filter(row => !row.error).length} successful pages; ${prerender.filter(row => row.error).length} failures.
- Browser: ${browserStructuralPassed}/${browser.length} representative viewport/page checks passed all locally testable structural and interaction checks; ${browserPassed} also completed external integrations and ${browserBlocked} were blocked by denied CDN/Firebase access. The Class 12 Physics sweep passed ${physicsStructuralPassed}/${physicsBrowser.length} structural mobile checks. Checks cover canonical/description/OG uniqueness, one H1, duplicate IDs, horizontal overflow, source integrity, console errors and solution interaction where present.
- Regression suite: URL normalization, redirect classification, metadata idempotence, protected public data/test routes, and placeholder eligibility.

Local browser tests intentionally stubbed advertising/analytics requests; other external CDN requests were allowed but denied by the sandbox and are reported as blocked rather than passed. This audit does not claim deployment, Search Console indexing, field Core Web Vitals, or production-cache validation. Production must be rechecked after deployment.

## Remaining audit findings

${failureLines}

The informational “little static content” signal is not treated as an error or a Google word-count rule. Directory pages and interactive tools can legitimately be concise; missing educational lessons are tracked separately in [seo-unavailable-resources.json](./seo-unavailable-resources.json) rather than padded with invented text.

## Reference policy

- [Google: canonical URL consolidation](https://developers.google.com/search/docs/crawling-indexing/consolidate-duplicate-urls)
- [Google: block indexing with noindex](https://developers.google.com/search/docs/crawling-indexing/block-indexing)
- [Google: JavaScript SEO basics](https://developers.google.com/search/docs/crawling-indexing/javascript/javascript-seo-basics)
- [Google Search Essentials for developers](https://developers.google.com/search/docs/fundamentals/get-started-developers)
`;
const output = path.join(ROOT, 'scripts/reports/seo-audit.md');
fs.writeFileSync(output, report);
console.log(`Wrote ${output}`);
if (bySeverity('error').length || bySeverity('warning').length) process.exitCode = 1;
