    function render() {
      renderTabs();
      renderCatTabs();
      renderStats();
      const md = monthData();

      let html = "";
      const items = filt(md[activeCat] || []);
      const cfg = catCfg[activeCat];
      let catHtml = "";
      if (items.length === 0) {
        catHtml = '<div class="empty-state reveal in"><strong>No matches for \u201c' + esc(search) + '\u201d</strong> in ' + activeMonth + ' ' + catLabels[activeCat] + '.<br>Try another keyword or pick a different month.</div>';
      } else {
        catHtml = '<section class="cat-card ' + cfg.cls + ' reveal">';
        catHtml += '<header class="cat-head"><div class="cat-id"><span class="cat-icon" aria-hidden="true">' + cfg.icon + '</span>';
        catHtml += '<div><h2 class="cat-title">' + cfg.label + '</h2><p class="cat-desc">' + cfg.desc + ' \u00b7 ' + activeMonth + ' 2026</p></div></div>';
        catHtml += '<span class="count-pill">' + items.length + ' ' + (items.length === 1 ? 'entry' : 'entries') + '</span></header>';
        catHtml += '<ol class="item-list">';
        catHtml += items.map((it, i) =>
          '<li class="item"><span class="idx">' + String(i + 1).padStart(2, "0") + '</span><div><p class="item-title">' + esc(it.who) + '</p><p class="item-desc">' + esc(it.what) + '</p></div></li>'
        ).join("");
        catHtml += '</ol></section>';
      }

      if (activeCat === "rbi") html += rateCardHtml();
      html += catHtml;

      html += '<aside class="ui-callout success reveal"><strong>\u{1F4CC} APFC Exam Focus \u2014 </strong>prioritise <strong>Repo 5.25% (neutral stance)</strong>, <strong>Fiscal Deficit FY27 BE 4.3%</strong> &amp; FY26 RE 4.4%, <strong>GDP FY26 7.4%</strong>, <strong>CPI June 4.38%</strong> (above 4% after 17 months), record <strong>GST of \u20B92.11 lakh crore (Jul)</strong>, <strong>forex reserves $701.4 bn</strong>, and the <strong>New Income Tax Act effective Apr 1, 2026</strong>.</aside>';

      $wrap.innerHTML = html;
      observeReveals();
    }

    /* ---- reveal-on-scroll ---- */
    function observeReveals() {
      const els = $wrap.querySelectorAll(".reveal:not(.in)");
      if (reduceMotion || !("IntersectionObserver" in window)) {
        els.forEach(el => el.classList.add("in"));
        return;
      }
      let d = 0;
      const io = new IntersectionObserver(entries => {
        entries.forEach(e => {
          if (!e.isIntersecting) return;
          e.target.style.transitionDelay = Math.min(d * 45, 240) + "ms";
          d++;
          e.target.classList.add("in");
          io.unobserve(e.target);
        });
      }, { rootMargin:"0px 0px -8% 0px" });
      els.forEach(el => io.observe(el));
    }

