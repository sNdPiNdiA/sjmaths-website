    /* ---- stats with animated counters ---- */
    function renderStats() {
      const md = monthData();
      const n = k => (md[k] || []).length;
      const items = [
        ["stat-rbi",     n("rbi"),     "RBI"],
        ["stat-budget",  n("budget"),  "Budget"],
        ["stat-economy", n("economy"), "Economy"],
        ["stat-months",  months.length, "Months"]
      ];
      $statRow.innerHTML = items.map(([cls, val, label]) =>
        `<div class="stat ${cls}"><span class="stat-num" data-target="${val}">${val}</span><span class="stat-label">${label}</span></div>`
      ).join("");
      if (!reduceMotion) {
        $statRow.querySelectorAll(".stat-num").forEach(el => {
          const target = +el.dataset.target, t0 = performance.now();
          el.textContent = "0";
          (function tick(t) {
            const p = Math.min((t - t0) / 550, 1), e = 1 - Math.pow(1 - p, 3);
            el.textContent = Math.round(target * e);
            if (p < 1) requestAnimationFrame(tick);
          })(t0);
        });
      }
    }

    /* ---- month & category tabs ---- */
    function renderTabs() {
      $tabs.innerHTML = `<span class="rail-pill" id="railPill" aria-hidden="true"></span>` +
        months.map(m =>
          `<button type="button" role="tab" class="month-btn${m === activeMonth ? " active" : ""}" data-month="${m}" aria-selected="${m === activeMonth}" tabindex="${m === activeMonth ? 0 : -1}">${m}</button>`
        ).join("");
      movePill();
    }

    function movePill() {
      const pill = document.getElementById("railPill");
      const btn = $tabs.querySelector(".month-btn.active");
      if (!pill || !btn) return;
      pill.style.width = btn.offsetWidth + "px";
      pill.style.transform = `translateX(${btn.offsetLeft - pill.offsetLeft}px)`;
      btn.scrollIntoView({ block:"nearest", inline:"nearest", behavior: reduceMotion ? "auto" : "smooth" });
    }

