// Auto-generate Hindi detail/exam/remember for topics without specific translations
function autoHindiDetail(t) {
    return `यह ${t.category} श्रेणी का एक महत्वपूर्ण करेंट अफेयर्स विषय है। ${t.detail}`;
}

function autoHindiExam(t) {
    return `${examPrefixHi} ${t.category} से संबंधित प्रश्न प्रतियोगी परीक्षाओं में पूछे जाते हैं।`;
}

function autoHindiRemember(t) {
    return `${rememberPrefixHi} ${t.remember}`;
}

let totalTopics = 0;
let translatedTitles = 0;

for (const file of files) {
    const filePath = path.join(DIR, file);
    const data = JSON.parse(fs.readFileSync(filePath, 'utf8'));

    data.topics.forEach(topic => {
        totalTopics++;
        const hiTitle = titleTranslations[topic.title] || topic.title;
        if (titleTranslations[topic.title]) translatedTitles++;

        topic.hi = {
            category: categoryHi[topic.category] || topic.category,
            title: hiTitle,
            importance: importanceHi[topic.importance] || topic.importance,
            facts: (topic.facts || []).map(f => f),
            detail: autoHindiDetail(topic),
            exam: autoHindiExam(topic),
            remember: autoHindiRemember(topic)
        };
    });

    fs.writeFileSync(filePath, JSON.stringify(data, null, 2), 'utf8');
    console.log(`Updated: ${file} (${data.topics.length} topics)`);
}

