// Helper to translate text using dictionary
function translateText(text) {
    if (typeof text !== 'string') return text;

    // Sort by length (longest first) to replace longer phrases first
    const sortedKeys = Object.keys(dict).sort((a, b) => b.length - a.length);

    let result = text;
    for (const key of sortedKeys) {
        if (result.includes(key)) {
            result = result.replace(new RegExp(escapeRegex(key), 'g'), dict[key]);
        }
    }
    return result;
}

function escapeRegex(string) {
    return string.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

// Process all files
let totalFiles = 0;
let totalTopics = 0;
let totalTranslations = 0;

for (const file of files) {
    const filePath = path.join(DIR, file);
    const data = JSON.parse(fs.readFileSync(filePath, 'utf8'));

    if (!data.topics || !Array.isArray(data.topics)) continue;

    totalFiles++;
    let fileTranslations = 0;

    for (const topic of data.topics) {
        totalTopics++;

        // Translate hi object fields
        if (topic.hi && typeof topic.hi === 'object') {
            // Translate facts array
            if (Array.isArray(topic.hi.facts)) {
                const newFacts = topic.hi.facts.map(f => {
                    const translated = translateText(f);
                    if (translated !== f) fileTranslations++;
                    return translated;
                });
                topic.hi.facts = newFacts;
            }

            // Translate detail
            if (topic.hi.detail) {
                const translated = translateText(topic.hi.detail);
                if (translated !== topic.hi.detail) fileTranslations++;
                topic.hi.detail = translated;
            }

            // Translate exam
            if (topic.hi.exam) {
                const translated = translateText(topic.hi.exam);
                if (translated !== topic.hi.exam) fileTranslations++;
                topic.hi.exam = translated;
            }

            // Translate remember
            if (topic.hi.remember) {
                const translated = translateText(topic.hi.remember);
                if (translated !== topic.hi.remember) fileTranslations++;
                topic.hi.remember = translated;
            }
        }
    }

    // Write updated file
    fs.writeFileSync(filePath, JSON.stringify(data, null, 2), 'utf8');
    totalTranslations += fileTranslations;
    console.log(`✓ ${file}: ${fileTranslations} translations applied`);
}

